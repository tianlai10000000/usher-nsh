use std::{env, fs, path::PathBuf};

fn main() {
    // NSH builds development hosts in debug and packaged runners in release.
    // An explicit override lets packaging and tests select either variant.
    println!("cargo:rerun-if-env-changed=USHER_MACOS_APPKIT");
    println!("cargo:rustc-check-cfg=cfg(usher_macos_appkit)");
    let appkit_enabled = match env::var_os("USHER_MACOS_APPKIT") {
        Some(value) => value == "1",
        None => env::var("PROFILE").as_deref() == Ok("debug"),
    };
    if env::var("CARGO_CFG_TARGET_OS").as_deref() == Ok("macos") && appkit_enabled {
        println!("cargo:rustc-cfg=usher_macos_appkit");
    }
    generate_bundled_theme_list();
}

/// Lists every theme file shipped under `ui/theme/` so adding a theme never requires a code change.
///
/// `builtin/<id>/theme.json` holds the base themes and `presets/*.json` the optional ones. The
/// runtime orders them by the `order` field of each file, so the discovery order here is only
/// kept stable for reproducible builds.
fn generate_bundled_theme_list() {
    let root = PathBuf::from(
        env::var_os("CARGO_MANIFEST_DIR").expect("CARGO_MANIFEST_DIR is set by Cargo"),
    )
    .join("ui/theme");
    println!("cargo:rerun-if-changed={}", root.display());

    let mut files = Vec::new();
    let builtin = root.join("builtin");
    if let Ok(entries) = fs::read_dir(&builtin) {
        for entry in entries.flatten() {
            let file = entry.path().join("theme.json");
            if file.is_file() {
                files.push(file);
            }
        }
    }
    if let Ok(entries) = fs::read_dir(root.join("presets")) {
        for entry in entries.flatten() {
            let file = entry.path();
            if file.extension().is_some_and(|ext| ext == "json") {
                files.push(file);
            }
        }
    }
    files.sort();

    let mut list = String::from(
        "/// Generated by `build.rs` from `ui/theme/`.\npub(crate) const BUNDLED_THEMES: &[&str] = &[\n",
    );
    for file in &files {
        // `{:?}` escapes the path as a Rust string literal on every platform.
        list.push_str(&format!(
            "    include_str!({:?}),\n",
            file.display().to_string()
        ));
    }
    list.push_str("];\n");
    let out = PathBuf::from(env::var_os("OUT_DIR").expect("OUT_DIR is set by Cargo"))
        .join("bundled_themes.rs");
    fs::write(out, list).expect("the build script can write to OUT_DIR");
}
